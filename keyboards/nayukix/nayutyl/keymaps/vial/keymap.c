void reset_eeprom(void) {
  eeconfig_init(); // EEPROMの初期化
}

bool process_record_user(uint16_t keycode, keyrecord_t *record) {
  if (record->event.pressed) {
    if (keycode == KC_F13) {
      reset_eeprom(); // EEPROMをリセット
      return false; // これ以上のキー処理を行わない
    }
  }
  return true;
}